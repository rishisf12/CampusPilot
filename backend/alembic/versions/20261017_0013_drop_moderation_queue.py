"""Drop `core.moderation_queue`.

The moderation feature was removed: the admin queue had no writer anywhere in
the backend, so it could never hold a row, and nothing in the app enqueues
content for review. The table was read-only against an empty set.

Dropped rather than left behind on purpose. Keeping it would fail the startup
drift check, which refuses to continue when a table exists in the database but
not in SQLModel.metadata - the app would not boot until the drift was resolved
anyway.

The drop is guarded on the table being empty. If a deployment somehow does have
queued content, the migration stops and says so rather than destroying a review
queue.

Upgrade is a no-op on databases that never had the table (fresh installs, and
the 0009 migration no longer creates it).
"""
